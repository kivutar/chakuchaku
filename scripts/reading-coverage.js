import "../reading.js";

// Editorial coverage, not learner statistics: one sentence is counted once per
// point, regardless of how many exercise directions reuse it.
export function createReadingCoverage(passages, grammarPoints) {
  globalThis.JlptN5Reading.validatePassages(passages);
  const pointsById = new Map(grammarPoints.map((point) => [point.id, point]));
  const references = new Map(grammarPoints.map((point) => [point.id, []]));
  for (const passage of passages) {
    for (const sentence of passage.sentences) {
      for (const id of sentence.grammarPointIds) {
        const point = pointsById.get(id);
        if (!point) throw new Error(`${sentence.id}: unknown reading grammar point ${id}.`);
        if (["n5", "n4"].indexOf(point.introducedAt) > ["n5", "n4"].indexOf(passage.level) ||
          !["n5", "n4"].includes(point.introducedAt)) {
          throw new Error(`${sentence.id}: grammar exceeds the reading's ${passage.level} level.`);
        }
        references.get(id).push({ passageId: passage.id, sentenceId: sentence.id });
      }
    }
  }
  const points = grammarPoints.map((point) => ({
    id: point.id, level: point.introducedAt, name: point.name, pattern: point.pattern,
    sentences: references.get(point.id).length,
    passages: new Set(references.get(point.id).map(({ passageId }) => passageId)).size,
    references: references.get(point.id)
  }));
  return {
    totalPassages: passages.length,
    totalSentences: passages.reduce((sum, passage) => sum + passage.sentences.length, 0),
    levels: ["n5", "n4"].map((level) => ({
      level,
      totalPoints: points.filter((point) => point.level === level).length,
      coveredPoints: points.filter((point) => point.level === level && point.sentences > 0).length,
      uncoveredPointIds: points.filter((point) => point.level === level && point.sentences === 0).map(({ id }) => id)
    })),
    passages: passages.map((passage) => ({
      id: passage.id, level: passage.level, title: passage.title,
      sentences: passage.sentences.length,
      grammarPointIds: [...new Set(passage.sentences.flatMap((sentence) => sentence.grammarPointIds))].sort()
    })),
    points
  };
}

export function formatReadingCoverage(coverage) {
  const escape = (value) => String(value || "").replaceAll("|", "\\|");
  const lines = [
    "# Reading grammar coverage", "",
    "Generated by `npm run content` from reviewed, explicit sentence tags. These are editorial statistics, not learner SRS progress. Tags identify selected constructions actually present; they are not an automatic or exhaustive linguistic analysis.", "",
    `${coverage.totalPassages} stories · ${coverage.totalSentences} sentences. A sentence counts once per point, not once per exercise direction.`, "",
    "## Stories", "", "| Story | Level | Sentences | Distinct points |", "| --- | --- | ---: | ---: |",
    ...coverage.passages.map((passage) => `| ${escape(passage.title.en)} | ${passage.level.toUpperCase()} | ${passage.sentences} | ${passage.grammarPointIds.length} |`)
  ];
  for (const level of coverage.levels) {
    lines.push("", `## ${level.level.toUpperCase()}`, "",
      `${level.coveredPoints} / ${level.totalPoints} points covered in the reading collection. Zero-count rows identify candidates for future stories.`, "",
      "| Point | Pattern | Sentences | Stories |", "| --- | --- | ---: | ---: |",
      ...coverage.points.filter((point) => point.level === level.level).map((point) => (
        `| ${escape(point.id)} | ${escape(point.pattern || point.name)} | ${point.sentences} | ${point.passages} |`
      )));
  }
  return `${lines.join("\n")}\n`;
}
